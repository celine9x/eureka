/** Icon */
export const Icon = ({
  name,
  type,
  variant = ICON_VARIANTS.outline,
  size = ICON_SIZES.md,
  color,
  style = {},
  ...props
}) => {
  // Determine icon set based on variant
  let iconSet;
  switch (variant) {
    case "fill":
    case "solid":
      iconSet = HeroiconsSolid;
      break;
    case "mini":
      iconSet = HeroiconsMini;
      break;
    case "outline":
    default:
      iconSet = HeroiconsOutline;
  }

  const iconInput = type ?? name;

  if (!iconInput) {
    console.warn('Icon requires either "name" or "type"');
    return null;
  }

  // Convert name to PascalCase with "Icon" suffix if needed
  const iconName = iconInput.endsWith("Icon") ? iconInput : `${iconInput}Icon`;
  const customIconKey = OBJECT_TYPE_NAME_MAP[normalizeObjectTypeName(iconInput)];
  const customIconDefinition = customIconKey ? OBJECT_TYPE_ICON_DEFS[customIconKey] : null;
  const IconComponent = iconSet[iconName];

  if (!customIconDefinition && !IconComponent) {
    console.warn(`Icon "${iconInput}" not found`);
    return null;
  }

  // Calculate pixel size
  const resolvedSize = typeof size === "number" ? size : SIZE_MAP[size] || "var(--size-icon-md)";

  const iconStyle = {
    ...styles.base,
    width: resolvedSize,
    height: resolvedSize,
    color: color || "currentColor",
    ...style,
  };

  if (customIconDefinition && variant === ICON_VARIANTS.fill) {
    return (
      <svg
        xmlns="http://www.w3.org/2000/svg"
        viewBox={customIconDefinition.viewBox}
        fill="none"
        style={iconStyle}
        {...props}
      >
        <image href={objectTypeFillSvg} x="0" y="0" width="174" height="612" />
      </svg>
    );
  }

  if (customIconDefinition) {
    return (
      <svg
        xmlns="http://www.w3.org/2000/svg"
        viewBox={customIconDefinition.viewBox}
        fill="none"
        style={iconStyle}
        {...props}
      >
        {customIconDefinition.paths.map((path, index) => (
          <path
            key={`${customIconKey}-${index}`}
            d={path.d}
            fill={path.fill || "currentColor"}
            fillRule={path.fillRule}
            clipRule={path.clipRule}
            stroke={path.stroke}
            strokeWidth={path.strokeWidth}
          />
        ))}
      </svg>
    );
  }

  return <IconComponent style={iconStyle} {...props} />;
};

